source("pre.R")
p <- function(l, e) { cat(l, ": "); r <- tr(e); if (inherits(r,"ERR")) print(r) else {dput(r)} }
rt <- function(df, ...) arrow_read(arrow_write(df, NULL, ...))
df3 <- structure(list(1:2, 3:4), class="data.frame", row.names=1:2)
p("NULL names", arrow_to_r(arrow_array(df3)))
p("rownames", arrow_to_r(arrow_array(data.frame(a=1:2, row.names=c("r1","r2")))))
p("0 col df n rows", arrow_to_r(arrow_array(data.frame(a=1:3)[, 0, drop=FALSE])))
p("0 col df ipc", rt(data.frame(a=1:3)[, 0, drop=FALSE]))
p("0 col df stream b=2", as.data.frame(arrow_stream(data.frame(a=1:3)[, 0, drop=FALSE], batch=2)))
p("0 row df", rt(data.frame(a=integer(), b=character(), f=factor(character(), levels=c("u","v")))))
p("0 row stream", as.data.frame(arrow_stream(data.frame(a=integer(), f=factor(character(), levels=c("u","v"))))))
p("0x0 df", rt(data.frame()))
p("nested df", {d <- data.frame(a=1:2); d$s <- data.frame(x=c("p","q"), y=c(NA,1.5)); rt(d)})
p("nested 0-col df", {d <- data.frame(a=1:2); d$s <- data.frame(x=1:2)[,0,drop=FALSE]; rt(d)})
p("matrix col", {d <- data.frame(a=1:2); d$m <- matrix(1:4,2); rt(d)})
p("list col", {d <- data.frame(a=1:2); d$l <- list(1:2, NULL); rt(d)})
p("df attr", {d <- data.frame(a=1:2); attr(d,"foo") <- "bar"; attr(d,"arrow_metadata") <- c(k="v"); attributes(rt(d))})
p("metadata arg", attributes(rt(data.frame(a=1), metadata=c(k="v", k="w", `é`="z"))))
p("metadata list raw", attributes(rt(data.frame(a=1), metadata=list(k=as.raw(c(0,255)), j="x"))))
p("metadata empty key", rt(data.frame(a=1), metadata=c("v")))
p("metadata empty val", attributes(rt(data.frame(a=1), metadata=c(k=""))))
p("metadata num", rt(data.frame(a=1), metadata=c(k=1)))
p("metadata factor", rt(data.frame(a=1), metadata=factor(c(k="a"))))
p("metadata list chr2", rt(data.frame(a=1), metadata=list(k=c("a","b"))))
p("metadata character(0)", attributes(rt(data.frame(a=1), metadata=character())))
p("tibble-ish", {d <- data.frame(a=1:2); class(d) <- c("tbl_df","tbl","data.frame"); class(rt(d))})
p("col attrs", {d <- data.frame(a=1:2); attr(d$a,"arrow_field_metadata") <- c(u="m", u="n"); attr(d$a, "arrow_extension") <- "my.ext"; attr(d$a,"arrow_extension_metadata") <- "{}"; attributes(rt(d)$a)})
p("ext meta raw NUL", {d <- data.frame(a=1:2); attr(d$a, "arrow_extension") <- "my.ext"; attr(d$a,"arrow_extension_metadata") <- as.raw(c(0,1)); attributes(rt(d)$a)})
p("ext meta chr2", {d <- data.frame(a=1:2); attr(d$a, "arrow_extension") <- "my.ext"; attr(d$a,"arrow_extension_metadata") <- c("a","b"); attributes(rt(d)$a)})
p("ext meta num", {d <- data.frame(a=1:2); attr(d$a, "arrow_extension") <- "my.ext"; attr(d$a,"arrow_extension_metadata") <- 5; attributes(rt(d)$a)})
p("ext meta NA", {d <- data.frame(a=1:2); attr(d$a, "arrow_extension") <- "my.ext"; attr(d$a,"arrow_extension_metadata") <- NA_character_; attributes(rt(d)$a)})
p("ext meta without ext", {d <- data.frame(a=1:2); attr(d$a,"arrow_extension_metadata") <- "zz"; attributes(rt(d)$a)})
p("ext empty", {d <- data.frame(a=1:2); attr(d$a, "arrow_extension") <- ""; attributes(rt(d)$a)})
p("field meta w/ ext keys", {d <- data.frame(a=1:2); attr(d$a,"arrow_field_metadata") <- c("ARROW:extension:name"="x.y"); attributes(rt(d)$a)})
p("field meta + ext both", {d <- data.frame(a=1:2); attr(d$a,"arrow_field_metadata") <- c("ARROW:extension:name"="x.y", q="1"); attr(d$a,"arrow_extension") <- "other"; attributes(rt(d)$a)})
p("factor w/ field md", {d <- data.frame(a=factor("a")); attr(d$a,"arrow_field_metadata") <- c(u="m"); list(attributes(rt(d)$a), attributes(rt(d, dictionary=FALSE)$a))})
p("bool8", {x <- structure(c(TRUE,NA,FALSE), arrow_extension="arrow.bool8"); arrow_to_r(arrow_array(x))})
p("ext on top-level", {x <- structure(1:2, arrow_extension="e", arrow_field_metadata=c(a="b")); arrow_to_r(arrow_array(x))})
