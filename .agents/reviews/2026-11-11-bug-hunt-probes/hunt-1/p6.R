na <- function(a) nanoarrow::as_nanoarrow_array(a)
show <- function(l, a, ...) { cat(l, ":\n"); z <- tr(zuarrow::arrow_to_r(na(a), lossy="character", ...)); if (inherits(z,"ERR")) return(print(z)); list(cbind(zu=as.character(z), arrow=as.character(a$cast(arrow::string())$as_vector())), quote=FALSE)
  back <- tr(zuarrow::arrow_array(z)); if (inherits(back,"ERR")) {cat("  BACK: "); print(back)} else { e <- tr(zuarrow::arrow_equal(back, na(a))); cat("  back equal: "); print(e) } }
i64 <- function(x) arrow::Array$create(x, type=arrow::string())$cast(arrow::int64())
mn <- "-9223372036854775808"; mx <- "9223372036854775807"
show("ts ns", i64(c(mn, "-9223372036854775807", mx, "-1", "0", "-1000000001", NA))$cast(timestamp("ns","UTC")))
show("ts us", i64(c(mn, mx, "-1", "253402300800000000", "-62135596800000001", "-62167219200000000"))$cast(timestamp("us","UTC")))
show("ts s", i64(c(mn, mx, "-1"))$cast(timestamp("s","UTC")))
show("ts ms naive", i64(c(mn, mx, "-1", "1500"))$cast(timestamp("ms")))
show("date64", i64(c(mn, mx, "-1", "86400000", "86400001"))$cast(date64()))
show("dur ns", i64(c(mn, mx, "-1"))$cast(duration("ns")))
show("time64 ns", i64(c("0","86399999999999","86400000000000","-1", mx))$cast(time64("ns")))
show("time32 s", arrow::Array$create(c(0L,86399L,86400L,-1L, NA))$cast(time32("s")))
show("time32 ms", arrow::Array$create(c(0L,86399999L,1L, -1L))$cast(time32("ms")))
