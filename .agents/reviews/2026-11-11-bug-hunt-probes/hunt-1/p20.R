# ALTREP
x <- c("é","日本語", NA, "", "a", strrep("z", 1000))
d <- data.frame(s=rep(x, 50)); bytes <- arrow_write(d, NULL, batch=7)
r1 <- arrow_read(bytes); r2 <- arrow_read(bytes, copy=FALSE)
p("altrep identical", identical(r1, r2)); p("is altrep", .Internal(inspect(r2$s)) -> z)
r2 <- arrow_read(bytes, copy=FALSE)$s
p("enc", table(Encoding(r2))); p("enc copy", table(Encoding(r1$s)))
r2 <- arrow_read(bytes, copy=FALSE)$s
p("subset first", identical(r2[c(300, 1, 3, 299)], r1$s[c(300,1,3,299)]))
p("oob idx", r2[c(301, 0, -1)][1:2])
p("anyNA/is.na", c(anyNA(r2), sum(is.na(r2))))
p("length", length(r2)); p("unique", identical(unique(r2), unique(r1$s)))
p("match", identical(match("a", r2), match("a", r1$s)))
p("saveRDS", {f <- tempfile(); r3 <- arrow_read(bytes, copy=FALSE)$s; saveRDS(r3, f); identical(readRDS(f), r1$s)})
p("serialize xdr=FALSE", {r3 <- arrow_read(bytes, copy=FALSE)$s; identical(unserialize(serialize(r3, NULL, xdr=FALSE)), r1$s)})
p("modify in place", {r3 <- arrow_read(bytes, copy=FALSE)$s; r3[2] <- "Q"; c(r3[1:3], length(r3))})
p("names<-", {r3 <- arrow_read(bytes, copy=FALSE)$s; names(r3) <- seq_along(r3); identical(unname(r3), r1$s)})
p("factor()", {r3 <- arrow_read(bytes, copy=FALSE)$s; identical(factor(r3), factor(r1$s))})
p("sort/order", {r3 <- arrow_read(bytes, copy=FALSE)$s; identical(order(r3), order(r1$s))})
p("paste", {r3 <- arrow_read(bytes, copy=FALSE)$s; identical(paste0(r3, "!"), paste0(r1$s, "!"))})
p("duplicate then gc", {r3 <- arrow_read(bytes, copy=FALSE)$s; r4 <- r3; rm(r3); gc(); identical(r4, r1$s)})
p("in df ops", {d2 <- arrow_read(bytes, copy=FALSE); d3 <- d2[d2$s %in% "a", , drop=FALSE]; nrow(d3)})
