source("pre.R")
p <- function(l, e) { cat(l, ": "); r <- tr(e); if (inherits(r,"ERR")) print(r) else {dput(r)} }
mi <- matrix(1:6, 3)
a <- arrow_array(mi, schema="i"); print(a); p("matrix schema i", arrow_to_r(a))
p("matrix schema g", arrow_to_r(arrow_array(matrix(c(1.5,2,3,4),2), schema="g")))
p("matrix chr schema u", arrow_to_r(arrow_array(matrix(letters[1:6],2), schema="u")))
p("matrix in stream w/ schema", {d <- data.frame(a=1:3); d$m <- mi; s <- arrow_schema(data.frame(a=1L, m=1L)); as.data.frame(arrow_stream(d, schema=s))})
p("matrix in df w/ schema array", {d <- data.frame(a=1:3); d$m <- mi; s <- arrow_schema(data.frame(a=1L, m=1L)); arrow_to_r(arrow_array(d, schema=s))})
p("1d array schema i", arrow_to_r(arrow_array(array(1:3), schema="i")))
md <- structure(c(1,2,3,4), dim=c(2L,2L), class="Date")
a <- arrow_array(md, schema=arrow_matrix()); print(a); p("date matrix", arrow_to_r(a)); 
mf <- structure(1:4, dim=c(2L,2L), levels=c("a","b","c","d"), class="factor")
a <- arrow_array(mf, schema=arrow_matrix()); print(a); p("factor matrix", arrow_to_r(a))
mp <- structure(c(1,2,3,4), dim=c(2L,2L), class=c("POSIXct","POSIXt"), tzone="UTC")
a <- tr(arrow_array(mp, schema=arrow_matrix())); print(a); p("posix matrix", arrow_to_r(a))
# nested df in list of df
d1 <- data.frame(a=1:2); d1$s <- data.frame(q=c("a","b")); x <- list(d1, d1[2,,drop=FALSE])
r <- suppressWarnings(arrow_to_r(arrow_array(x))); print(identical(r, x)); str(r)
x2 <- list(d1, d1); r <- arrow_to_r(arrow_array(x2)); print(identical(r,x2))
# explicit schema vs data frame column count / names
p("schema fewer cols", arrow_to_r(arrow_array(data.frame(a=1:2,b=3:4), schema=arrow_schema(data.frame(a=1L)))))
p("schema more cols", arrow_to_r(arrow_array(data.frame(a=1:2), schema=arrow_schema(data.frame(a=1L,b=1L)))))
p("schema other names", arrow_to_r(arrow_array(data.frame(a=1:2,b=c("x","y")), schema=arrow_schema(data.frame(b=1L,a="")))))
p("schema swapped types", arrow_to_r(arrow_array(data.frame(a=1:2,b=c("x","y")), schema=arrow_schema(data.frame(b="",a=1L)))))
p("vector w/ struct schema", arrow_to_r(arrow_array(1:2, schema=arrow_schema(data.frame(a=1L)))))
p("df w/ int schema", arrow_to_r(arrow_array(data.frame(a=1:2), schema="i")))
p("list w/ int schema", arrow_to_r(arrow_array(list(1L,2L), schema="i")))
p("list w/ struct schema", arrow_to_r(arrow_array(list(a=1:2, b=3:4), schema=arrow_schema(data.frame(a=1L,b=1L)))))
p("factor w/ dict schema ordered", arrow_to_r(arrow_array(factor(c("a","b")), schema=arrow_schema(factor("z", ordered=TRUE)))))
p("chr w/ dict schema", arrow_to_r(arrow_array(c("a","b","a"), schema=arrow_schema(factor("z")))))
p("int w/ dict schema", arrow_to_r(arrow_array(c(1L,5L), schema=arrow_schema(factor("z")))))
p("schema nullable flag off + NA", {sp <- zuarrow:::zar_spec("i", "", flags=0L); s <- .Call(zuarrow:::zar_c_schema_from_spec, sp); a <- arrow_array(c(1L,NA), schema=s); arrow_to_r(a)})
p("stream schema given", {s <- arrow_schema(data.frame(a=1, b="")); as.data.frame(arrow_stream(data.frame(a=1:3, b=letters[1:3]), batch=2, schema=s))})
p("stream of vector", arrow_to_r(arrow_stream(1:5, batch=2)))
p("stream of vector next", arrow_next(arrow_stream(1:5, batch=2)))
p("stream of list", arrow_to_r(arrow_stream(list(1:2, 3L, NULL), batch=2)))
p("stream of factor", arrow_to_r(arrow_stream(factor(c("a","b","a","c")), batch=1)))
p("stream schema='tsu:' string", arrow_to_r(arrow_stream(as.POSIXct(1:3, tz="UTC"), batch=2, schema="tss:UTC")))
p("stream matrix", arrow_to_r(arrow_stream(matrix(1:6,3), batch=2, schema=arrow_matrix()), to=arrow_matrix()))
p("as.data.frame non-struct stream", as.data.frame(arrow_stream(1:5)))
p("as.vector struct", as.vector(arrow_array(data.frame(a=1))))
p("as.vector mode", as.vector(arrow_array(1:3), "list"))
p("as.vector", as.vector(arrow_array(1:3)))
p("as.character", as.character(arrow_array(1:3)))
p("as.list", as.list(arrow_array(1:3)))
p("length", length(arrow_array(1:3)))
p("as.data.frame row.names", as.data.frame(arrow_array(data.frame(a=1)), row.names="x"))
p("as.data.frame optional", as.data.frame(arrow_array(data.frame(`a b`=1, check.names=FALSE)), optional=TRUE))
p("data.frame(stream)", data.frame(arrow_stream(data.frame(a=1:2))))
