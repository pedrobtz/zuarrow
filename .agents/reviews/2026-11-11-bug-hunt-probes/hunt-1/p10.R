source("pre.R")
p <- function(l, e) { cat(l, ": "); r <- tr(e); if (inherits(r,"ERR")) print(r) else {str(r)} }
df <- data.frame(a=1:5, b=letters[1:5], f=factor(c("x","y","x","z","y")))
nb <- function(s) { n <- 0; while (!is.null(arrow_next(s))) n <- n+1; n }
for (b in list(1, 2, 5, 6, 2.0, 2^31, 2^53, Inf, 1e300, 0, -1, 2.5, NA, NA_integer_, "2", TRUE, c(1,2), NULL, 2L, 0.5)) p(paste("batch", deparse(b)), nb(arrow_stream(df, batch=b)))
for (b in list(Inf, 2^31, 0, 2.5, "2", TRUE, NULL, NA)) p(paste("write batch", deparse(b)), identical(arrow_read(arrow_write(df, NULL, batch=b)), df))
for (l in list(NA, 0, 1, 3.5, 100, -100, -1e10, 1e10, Inf, "3", TRUE, 2^31, c(1,2))) for (cc in c("zstd","lz4","none")) p(paste(cc, "level", deparse(l)), identical(arrow_read(arrow_write(df, NULL, compression=cc, level=l)), df))
p("limits neg", arrow_limits(max_message=-1))
p("limits NA", arrow_limits(max_depth=NA))
p("limits frac", arrow_limits(max_depth=0.5)$max_depth)
p("limits Inf", unclass(arrow_limits(max_message=Inf, max_depth=Inf, max_batch_rows=Inf, max_dictionary=Inf)))
bytes <- arrow_write(df, NULL)
p("read lim Inf", identical(arrow_read(bytes, limits=arrow_limits(max_message=Inf, max_depth=Inf, max_batch_rows=Inf, max_dictionary=Inf)), df))
p("read lim 1e300", identical(arrow_read(bytes, limits=arrow_limits(max_message=1e300, max_batch_rows=1e300, max_dictionary=1e300, max_bytes=1e300)), df))
p("read lim 2^63", identical(arrow_read(bytes, limits=arrow_limits(max_message=2^63, max_batch_rows=2^63, max_dictionary=2^64, max_bytes=2^63)), df))
p("read depth 0", arrow_read(bytes, limits=arrow_limits(max_depth=0)))
p("read depth 1", identical(arrow_read(bytes, limits=arrow_limits(max_depth=1)),df))
p("read rows 4.5", arrow_read(bytes, limits=arrow_limits(max_batch_rows=4.5)))
p("read rows 5", identical(arrow_read(bytes, limits=arrow_limits(max_batch_rows=5)),df))
p("read rows 5.5",identical(arrow_read(bytes, limits=arrow_limits(max_batch_rows=5.5)),df))
p("read rows 0.5", arrow_read(arrow_write(df[0,], NULL), limits=arrow_limits(max_batch_rows=0.5)))
p("read bytes exact", identical(arrow_read(bytes, limits=arrow_limits(max_bytes=length(bytes))),df))
p("read bytes -1", arrow_read(bytes, limits=arrow_limits(max_bytes=length(bytes)-1)))
p("read bytes -.5", arrow_read(bytes, limits=arrow_limits(max_bytes=length(bytes)-0.5)))
p("read msg 0", arrow_read(bytes, limits=arrow_limits(max_message=0)))
p("limits modified", {l <- arrow_limits(); l$max_depth <- NA_integer_; arrow_read(bytes, limits=l)})
p("limits modified2", {l <- arrow_limits(); l$max_message <- "a"; arrow_read(bytes, limits=l)})
p("limits modified3", {l <- arrow_limits(); l$max_message <- NULL; arrow_read(bytes, limits=l)})
p("limits modified4", {l <- arrow_limits(); l$max_message <- c(1,2); arrow_read(bytes, limits=l)})
p("limits reorder", {l <- arrow_limits(max_bytes=10); l <- structure(rev(unclass(l)), class="zuarrow_limits"); arrow_read(bytes, limits=l)})
print(arrow_limits())
